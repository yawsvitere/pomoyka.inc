#!/usr/bin/env bash
set -Eeuo pipefail
umask 077

APP_DIR=/opt/pomoyka.inc
RAW_BASE=https://raw.githubusercontent.com/yawsvitere/pomoyka.inc/main

if [[ "$(id -u)" -ne 0 ]]; then
  echo "Запусти установщик от root: curl -fsSL $RAW_BASE/install.sh | sudo bash" >&2
  exit 1
fi

if ! command -v curl >/dev/null 2>&1; then
  if command -v apt-get >/dev/null 2>&1; then
    apt-get update
    apt-get install -y ca-certificates curl
  else
    echo "Установи curl и запусти скрипт повторно." >&2
    exit 1
  fi
fi

if ! command -v docker >/dev/null 2>&1 || ! docker compose version >/dev/null 2>&1; then
  curl -fsSL https://get.docker.com | sh
fi

if ! docker compose version >/dev/null 2>&1 && command -v apt-get >/dev/null 2>&1; then
  apt-get update
  apt-get install -y docker-compose-plugin
fi

if ! docker compose version >/dev/null 2>&1; then
  echo "Docker Compose Plugin не найден." >&2
  exit 1
fi

if ! command -v openssl >/dev/null 2>&1; then
  if command -v apt-get >/dev/null 2>&1; then
    apt-get update
    apt-get install -y openssl
  else
    echo "Установи openssl и запусти скрипт повторно." >&2
    exit 1
  fi
fi

mkdir -p "$APP_DIR"
cd "$APP_DIR"

download_file() {
  local name="$1"
  local destination="$2"
  curl -fsSL "$RAW_BASE/$name" -o "$destination.tmp"
  mv "$destination.tmp" "$destination"
}

download_file docker-compose.prod.yml docker-compose.prod.yml

if [[ ! -f .env ]]; then
  if [[ ! -r /dev/tty ]]; then
    echo "Для первоначальной настройки нужен интерактивный терминал." >&2
    exit 1
  fi

  read -r -p "Email администратора: " admin_email </dev/tty
  if [[ ! "$admin_email" =~ ^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$ ]]; then
    echo "Ошибка: введён некорректный email." >&2
    exit 1
  fi

  read -r -p "Публичный адрес сайта для S3 (домен или IP[:порт], без схемы): " s3_public_endpoint </dev/tty
  if [[ ! "$s3_public_endpoint" =~ ^[A-Za-z0-9.:-]+$ ]]; then
    echo "Ошибка: укажи домен или IP[:порт] без http://, https:// и пути." >&2
    exit 1
  fi

  read -r -p "Публичный S3 доступен через HTTPS? [y/N] " s3_public_use_ssl </dev/tty
  case "$s3_public_use_ssl" in
    [Yy]|[Yy][Ee][Ss]) s3_public_use_ssl=true ;;
    *) s3_public_use_ssl=false ;;
  esac

  postgres_user="feed_$(openssl rand -hex 6)"
  postgres_password="$(openssl rand -hex 32)"
  s3_access_key="storage$(openssl rand -hex 6)"
  s3_secret_key="$(openssl rand -hex 32)"
  jwt_secret="$(openssl rand -hex 64)"
  dataprotection_password="$(openssl rand -hex 64)"

  cat > .env <<EOF
# Generated by install.sh. Keep this file private.
POSTGRES_USER=$postgres_user
POSTGRES_PASSWORD=$postgres_password
POSTGRES_DB=feeddb

S3_ACCESS_KEY=$s3_access_key
S3_SECRET_KEY=$s3_secret_key
S3_BUCKET=feed-files
S3_PUBLIC_ENDPOINT=$s3_public_endpoint
S3_PUBLIC_USE_SSL=$s3_public_use_ssl

JWT_SECRET=$jwt_secret
ADMIN_EMAIL=$admin_email
DATAPROTECTION_CERT_PASSWORD=$dataprotection_password
EOF
  chmod 600 .env
fi

echo "Загружаю готовые production-образы..."
if ! docker compose -f docker-compose.prod.yml pull; then
  echo "Не удалось загрузить образы. Проверь, что пакеты pomoyka-inc-backend и pomoyka-inc-frontend в GHCR публичные." >&2
  exit 1
fi

docker compose -f docker-compose.prod.yml up -d

echo
echo "Установка завершена. Сайт доступен на порту 3000."
echo "Статус: cd $APP_DIR && docker compose -f docker-compose.prod.yml ps"
